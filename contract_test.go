var update = flag.Bool("update", false, "rewrite the golden files")

// contractGolden is what the server sends the client, as TypeScript: `tsc` checks it against the generated types
// (mise r quality:typecheck), so Go and TypeScript cannot drift apart unnoticed.
const contractGolden = "frontend/generated/contract.golden.ts"

// everyWidget is a dashboard with one widget of each registered type.
func everyWidget() *dashboard.Builder {
	logs := sql.New(sql.From("http_logs"))
	return dashboard.New().
		WithTitle("Shop").
		DefaultTimeRange("168h").
		FilterButton("Errors", "status >= 500").
		Widget(widget.NewMarkdown().Content("# Shop")).
		Widget(widget.NewGrid().Template("a b").
			Area("a", widget.NewTimeBar(logs).X(sql.Timestamp15Min()).Y(sql.Count()).Fill(sql.Field("status")).Title("Requests")).
			Area("b", widget.NewTimeLine(logs).X(sql.AutoBucket("timestamp")).Y(sql.Count()).Title("Requests over time"))).
		Widget(widget.NewCollapsibleGroup().Title("Details").Open().
			Widget(widget.NewBarVertical(logs).X(sql.Field("status")).Y(sql.Count())).
			Widget(widget.NewBarHorizontal(logs).X(sql.Count()).Y(sql.Field("path"))).
			Widget(widget.NewTimeHeatmap(logs).X(sql.Timestamp15Min()).Y(sql.Field("duration_ms")).YBucketSize(100)).
			Widget(widget.NewTimeHeatmapOrdinal(logs).X(sql.Timestamp15Min()).Y(sql.Enum("status"))).
			Widget(widget.NewStats(logs).Id("shop_stats")).
			Widget(widget.NewTable(logs).Title("Latest").Limit(100))).
		Widget(widget.NewCheckboxGroup("level", "Level", []string{"error", "warn"})).
		Widget(widget.NewTextInput("path", "Path").Placeholder("/api")).
		Widget(widget.NewSchemaTable("http_logs")).
		Widget(widget.NewSpeedscopeLink(logs)).
		Widget(widget.NewAlertOverview("shop%")).
		Widget(widget.NewAlertDetail("shop", "login_events"))
}

func TestContract_Golden(t *testing.T) {
	logger := zerolog.New(zerolog.NewTestWriter(t))
	mux := http.NewServeMux()
	d := newDashicaImpl(&config.Config{}, logger, mux, rendering.Dependencies{
		ClickhouseClientManager: clickhouse.NewManager(&config.Config{}, logger),
		Logger:                  logger,
	})
	d.RegisterDashboardGroup("Shop").RegisterDashboard("/p/shop", everyWidget())

	workbench := get(t, mux, "/workbench.json")
	page := get(t, mux, "/p/shop/page.json")
	home := get(t, mux, "/page.json")
	if missing := missingTypes(t, page); len(missing) > 0 {
		t.Errorf("everyWidget lacks %v", missing)
	}

	golden := "// Code generated by TestContract_Golden (contract_test.go, `go test . -update`); DO NOT EDIT.\n" +
		"// What the server sends for everyWidget and the start page: tsc checks it against the generated types.\n" +
		"import type { PageJson, WorkbenchJson } from './zz_generated.dashica';\n\n" +
		"export const workbench = " + workbench + " satisfies WorkbenchJson;\n\n" +
		"export const page = " + page + " satisfies PageJson;\n\n" +
		"export const home = " + home + " satisfies PageJson;\n"
	if *update {
		if err := os.WriteFile(contractGolden, []byte(golden), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(contractGolden)
	if err != nil || string(want) != golden {
		t.Errorf("%s is not what the server sends (err %v); rewrite it with `go test . -run TestContract_Golden -update` and review the diff", contractGolden, err)
	}
}

// get is the indented JSON the server answers to GET `path`.
func get(t *testing.T, mux *http.ServeMux, path string) string {
	t.Helper()
	rec := httptest.NewRecorder()
	mux.ServeHTTP(rec, httptest.NewRequest(http.MethodGet, path, nil))
	if rec.Code != http.StatusOK {
		t.Fatalf("GET %s: %d %s", path, rec.Code, rec.Body)
	}
	var out bytes.Buffer
	if err := json.Indent(&out, bytes.TrimSpace(rec.Body.Bytes()), "", "  "); err != nil {
		t.Fatalf("GET %s: %v", path, err)
	}
	return out.String()
}

// missingTypes are the registered widget types page.json does not contain.
func missingTypes(t *testing.T, page string) []string {
	t.Helper()
	var p dashboard.PageJson
	if err := json.Unmarshal([]byte(page), &p); err != nil {
		t.Fatal(err)
	}
	seen := map[string]bool{}
	var walk func(nodes []widget.Node)
	walk = func(nodes []widget.Node) {
		for _, n := range nodes {
			seen[n.Type] = true
			for _, child := range n.Children {
				walk([]widget.Node{child})
			}
		}
	}
	walk(p.Widgets)
	var missing []string
	for _, typ := range widget.RegisteredWidgetTypes() {
		if !seen[typ] {
			missing = append(missing, typ)
		}
	}
	slices.Sort(missing)
	return missing
}
