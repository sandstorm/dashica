// The Go types whose wire forms the widget props use (sql.MarshalFieldProps, color.ColorScale.MarshalJSON), and the
// node of page.json.
const (
	sqlFieldPropsDTO = "github.com/sandstorm/dashica/lib/dashboard/sql.sqlFieldPropsDTO"
	colorScaleDTO    = "github.com/sandstorm/dashica/lib/dashboard/color.colorScaleDTO"
	widgetNode       = widgetPkgPath + ".Node"
)

// emitTS writes the TypeScript types of what the server sends: every widget's props, the Widget union, WidgetNode
// (widget.Node) and the DTOs named in `dtoNames` ("github.com/sandstorm/dashica/lib/dashboard.PageJson") with every
// struct they reference.
func emitTS(m *model, dtoNames []string, outFile string) error {
	e, err := loadDTOs(append([]string{sqlFieldPropsDTO, colorScaleDTO, widgetNode}, dtoNames...))
	if err != nil {
		return err
	}
	var out strings.Builder
	out.WriteString(tsHeader)
	if err := e.interfaces(sqlFieldPropsDTO, colorScaleDTO); err != nil {
		return err
	}
	for _, g := range collectGroups(m) {
		writeTSInterface(&e.out, g.GroupType, "", g.Group)
	}
	for _, w := range m.widgets {
		writeTSInterface(&e.out, w.TypeName+"Props", "Props of the "+w.Title+" widget (`"+w.WireName+"`).", propsFields(w))
	}
	if err := e.widgetNode(m); err != nil {
		return err
	}
	if err := e.interfaces(dtoNames...); err != nil {
		return err
	}
	out.WriteString(e.out.String())

	path := outFile
	if !filepath.IsAbs(path) {
		path = filepath.Join(m.pkgDir, outFile)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(out.String()), 0o644)
}

const tsHeader = `// Code generated by cmd/dashica-gen from the Go widgets and DTOs; DO NOT EDIT.
// The types of what the server sends: the widgets of page.json, page.json, workbench.json.

`

// tsName is the TypeScript name of the Go type `goType` (<import path>.<Type>): capitalized, without a "DTO" suffix
// (sqlFieldPropsDTO → SqlFieldProps); widget.Node is WidgetNode, as the Widget union names the widget.
func tsName(goType string) string {
	if goType == widgetNode {
		return "WidgetNode"
	}
	name := strings.TrimSuffix(goType[strings.LastIndex(goType, ".")+1:], "DTO")
	return strings.ToUpper(name[:1]) + name[1:]
}

func writeTSInterface(out *strings.Builder, name, doc string, fields []fieldInfo) {
	if doc != "" {
		fmt.Fprintf(out, "/** %s */\n", doc)
	}
	fmt.Fprintf(out, "export interface %s {\n", name)
	for _, f := range fields {
		writeTSDoc(out, f.Doc)
		optional := "?"
		if f.Required {
			optional = ""
		}
		fmt.Fprintf(out, "  %s%s: %s;\n", f.JSONKey, optional, tsOfField(f))
	}
	out.WriteString("}\n\n")
}

func writeTSDoc(out *strings.Builder, doc string) {
	if doc == "" {
		return
	}
	lines := strings.Split(doc, "\n")
	if len(lines) == 1 {
		fmt.Fprintf(out, "  /** %s */\n", doc)
		return
	}
	out.WriteString("  /**\n")
	for _, line := range lines {
		fmt.Fprintf(out, "   * %s\n", strings.TrimSpace(line))
	}
	out.WriteString("   */\n")
}

func tsOfField(f fieldInfo) string {
	switch f.Category {
	case catField, catTsField, catOptField:
		return tsName(sqlFieldPropsDTO)
	case catString:
		return "string"
	case catInt, catInt64, catPtrInt:
		return "number"
	case catBool, catPtrBool:
		return "boolean"
	case catColor:
		return tsName(colorScaleDTO)
	case catKeyValue:
		return "Record<string, string>"
	case catStringList:
		return "string[]"
	case catGroup:
		return f.GroupType
	case catEnum:
		values := make([]string, len(f.EnumOptions))
		for i, v := range f.EnumOptions {
			values[i] = "'" + v.Str + "'"
		}
		return strings.Join(values, " | ")
	}
	panic("tsOfField: unhandled category " + string(f.Category))
}

// loadDTOs loads the packages of the Go types `names` (<import path>.<Type>) for writing their interfaces.
func loadDTOs(names []string) (*dtoEmitter, error) {
	var pkgPaths []string
	for _, name := range names {
		dot := strings.LastIndex(name, ".")
		if dot < 0 {
			return nil, fmt.Errorf("ts type %q: want <import path>.<Type>", name)
		}
		if !slices.Contains(pkgPaths, name[:dot]) {
			pkgPaths = append(pkgPaths, name[:dot])
		}
	}
	pkgs, err := packages.Load(&packages.Config{Mode: packages.NeedName | packages.NeedTypes | packages.NeedSyntax | packages.NeedDeps | packages.NeedImports}, pkgPaths...)
	if err != nil {
		return nil, fmt.Errorf("load ts types: %w", err)
	}
	if packages.PrintErrors(pkgs) > 0 {
		return nil, fmt.Errorf("packages of the ts types have errors")
	}
	e := &dtoEmitter{docs: map[string]string{}, pkgs: map[string]*types.Package{}, done: map[string]bool{}, enums: map[string]enumInfo{}}
	for _, pkg := range pkgs {
		if err := collectEnums(pkg, e.enums); err != nil {
			return nil, err
		}
	}
	packages.Visit(pkgs, nil, func(pkg *packages.Package) {
		e.pkgs[pkg.PkgPath] = pkg.Types
		for key, doc := range harvestDocs(pkg) {
			e.docs[pkg.PkgPath+"."+key] = doc
		}
		for key, doc := range harvestTypeDocs(pkg) {
			e.docs[pkg.PkgPath+"."+key] = doc
		}
	})
	return e, nil
}

// dtoEmitter writes the interfaces of Go structs, each once, after those of the structs it references.
type dtoEmitter struct {
	docs  map[string]string
	pkgs  map[string]*types.Package
	done  map[string]bool
	enums map[string]enumInfo // by "<import path>.<Type>"
	out   strings.Builder
}

// interfaces writes the interfaces of the Go types `names` (<import path>.<Type>).
func (e *dtoEmitter) interfaces(names ...string) error {
	for _, name := range names {
		named, err := e.lookup(name)
		if err != nil {
			return err
		}
		if err := e.emit(named); err != nil {
			return err
		}
	}
	return nil
}

func (e *dtoEmitter) lookup(name string) (*types.Named, error) {
	dot := strings.LastIndex(name, ".")
	pkg := e.pkgs[name[:dot]]
	if pkg == nil {
		return nil, fmt.Errorf("ts type %s: package not loaded", name)
	}
	obj := pkg.Scope().Lookup(name[dot+1:])
	if obj == nil {
		return nil, fmt.Errorf("ts type %s not found", name)
	}
	named, ok := obj.Type().(*types.Named)
	if !ok {
		return nil, fmt.Errorf("ts type %s is no named type", name)
	}
	return named, nil
}

// emit writes the interface of `named` (a struct) after those of the structs it references.
func (e *dtoEmitter) emit(named *types.Named) error {
	goType := qualified(named)
	if e.done[goType] {
		return nil
	}
	e.done[goType] = true
	body, err := e.fields(named)
	if err != nil {
		return err
	}
	fmt.Fprintf(&e.out, "/** %s */\nexport interface %s {\n%s}\n\n", e.typeDoc(named), tsName(goType), body)
	return nil
}

// widgetNode writes WidgetNode, widget.Node per widget type: its props, `dataUrl` when it has data, `children`
// when it has children fields (both as Mount sets them).
func (e *dtoEmitter) widgetNode(m *model) error {
	named, err := e.lookup(widgetNode)
	if err != nil {
		return err
	}
	e.done[widgetNode] = true
	fmt.Fprintf(&e.out, "/** %s */\nexport type WidgetNode =", e.typeDoc(named))
	for _, w := range m.widgets {
		fmt.Fprintf(&e.out, "\n  | { type: '%s'; props: %sProps", w.WireName, w.TypeName)
		if w.HasData {
			e.out.WriteString("; dataUrl: string")
		}
		if hasChildren(w) {
			e.out.WriteString("; children?: Record<string, WidgetNode>")
		}
		e.out.WriteString(" }")
	}
	e.out.WriteString(";\n\nexport type WidgetType = WidgetNode['type'];\n\n")
	return nil
}

// hasChildren: `w` lays out other widgets (a grid's areas, a group's widgets); Mount puts them into its children.
func hasChildren(w widgetInfo) bool {
	for _, f := range w.Fields {
		if f.Category == catChildrenList || f.Category == catChildrenMap {
			return true
		}
	}
	return false
}

// fields is the TypeScript members of the struct `named` without the JSON keys `skip`, with their docs.
func (e *dtoEmitter) fields(named *types.Named, skip ...string) (string, error) {
	st, ok := named.Underlying().(*types.Struct)
	if !ok {
		return "", fmt.Errorf("ts type %s is no struct", qualified(named))
	}
	var body strings.Builder
	for i := 0; i < st.NumFields(); i++ {
		f := st.Field(i)
		key, omitempty := jsonTag(st.Tag(i))
		if key == "" {
			key = f.Name()
		}
		if !f.Exported() || key == "-" || slices.Contains(skip, key) {
			continue
		}
		ts, optional, err := e.tsOf(f.Type())
		if err != nil {
			return "", fmt.Errorf("%s.%s: %w", qualified(named), f.Name(), err)
		}
		writeTSDoc(&body, e.docs[qualified(named)+"."+f.Name()])
		mark := ""
		if omitempty || optional {
			mark = "?"
		}
		fmt.Fprintf(&body, "  %s%s: %s;\n", key, mark, ts)
	}
	return body.String(), nil
}

func qualified(named *types.Named) string {
	return named.Obj().Pkg().Path() + "." + named.Obj().Name()
}

// harvestTypeDocs maps each type of `pkg` to its doc comment.
func harvestTypeDocs(pkg *packages.Package) map[string]string {
	out := map[string]string{}
	for _, file := range pkg.Syntax {
		for _, decl := range file.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts := spec.(*ast.TypeSpec)
				doc := ts.Doc
				if doc == nil && len(gd.Specs) == 1 {
					doc = gd.Doc
				}
				if text := strings.TrimSpace(doc.Text()); text != "" {
					out[ts.Name.Name] = text
				}
			}
		}
	}
	return out
}

// typeDoc is the first sentence of the type's doc comment and its Go name, for the interface's comment.
func (e *dtoEmitter) typeDoc(named *types.Named) string {
	where := named.Obj().Pkg().Name() + "." + named.Obj().Name()
	doc := strings.Join(strings.Fields(e.docs[qualified(named)]), " ")
	if doc == "" {
		return where
	}
	if end := strings.Index(doc, ". "); end >= 0 {
		doc = doc[:end+1]
	}
	return doc + " (" + where + ")"
}

// tsOf is the TypeScript type of a field of type `t`, and whether it may be absent (a pointer).
func (e *dtoEmitter) tsOf(t types.Type) (string, bool, error) {
	switch t := t.(type) {
	case *types.Pointer:
		ts, _, err := e.tsOf(t.Elem())
		return ts, true, err
	case *types.Basic:
		switch {
		case t.Info()&types.IsString != 0:
			return "string", false, nil
		case t.Info()&types.IsBoolean != 0:
			return "boolean", false, nil
		case t.Info()&types.IsNumeric != 0:
			return "number", false, nil
		}
	case *types.Slice:
		elem, _, err := e.tsOf(t.Elem())
		return elem + "[]", false, err
	case *types.Map:
		elem, _, err := e.tsOf(t.Elem())
		return "Record<string, " + elem + ">", false, err
	case *types.Named:
		switch qualified(t) {
		case widgetNode:
			return tsName(widgetNode), false, nil
		case "encoding/json.RawMessage":
			return "unknown", false, nil
		}
		if enum, ok := e.enums[qualified(t)]; ok {
			values := make([]string, len(enum.Values))
			for i, v := range enum.Values {
				values[i] = "'" + v.Str + "'"
			}
			return strings.Join(values, " | "), false, nil
		}
		if _, ok := t.Underlying().(*types.Struct); ok {
			return tsName(qualified(t)), false, e.emit(t)
		}
		return e.tsOf(t.Underlying())
	}
	return "", false, fmt.Errorf("no TypeScript type for %s", t)
}

// jsonTag is the key of a `json:"…"` tag and whether it says omitempty or omitzero (an enum, a struct).
func jsonTag(tag string) (string, bool) {
	key, opts, _ := strings.Cut(reflect.StructTag(tag).Get("json"), ",")
	return key, strings.Contains(","+opts+",", ",omitempty,") || strings.Contains(","+opts+",", ",omitzero,")
}
